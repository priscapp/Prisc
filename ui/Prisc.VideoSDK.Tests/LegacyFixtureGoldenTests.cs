        [Fact]
        public void Overlays_ride_a_sped_host_and_outlive_it()
        {
            const string F = "sped-segment";

            AssertHosted(F, Cursor, 12 * Sec, "Screen", 14 * Sec, speed: 2.0);
            AssertHosted(F, Cursor, 25 * Sec, "Screen", 22 * Sec + Sec / 2, speed: 0.5);
            AssertHosted(F, Keyboard, 25 * Sec, "Screen", 22 * Sec + Sec / 2, speed: 0.5);

            // the 2x screen clip ended at 15 s; its overlay clips run to 20 s
            Assert.Null(Golden(F, Cursor, 17 * Sec).SourceTicks);
            var keys = Golden(F, Keyboard, 17 * Sec);
            Assert.Null(keys.Host);
            Assert.Equal(7 * Sec, keys.SourceTicks);
            Assert.Equal(1.0, keys.Speed);
        }

        [Fact]
        public void A_duplicate_row_hosts_only_where_the_grouped_screen_is_gone()
        {
            const string F = "duplicate-row";

            // the copy is the backmost clip here, showing 2 s of source, and the screen still wins
            AssertHosted(F, Cursor, 5 * Sec, "Screen", 5 * Sec);
            AssertHosted(F, Keyboard, 5 * Sec, "Screen", 5 * Sec);
            Assert.Equal(new[] { 0f, 0f, 1280f, 720f }, Golden(F, Cursor, 5 * Sec).Dest);

            // in the hole it falls to the copy, 3 s behind. Scale .4 at (.25, .25): 512x288 centred
            // on (320, 180)
            AssertHosted(F, Cursor, 25 * Sec, "Screen copy", 22 * Sec);
            AssertHosted(F, Keyboard, 25 * Sec, "Screen copy", 22 * Sec);
            Assert.Equal(new[] { 64f, 36f, 576f, 324f }, Golden(F, Cursor, 25 * Sec).Dest);
        }

        [Fact]
        public void A_duplicate_left_in_front_does_not_take_over_from_the_screen()
        {
            const string F = "duplicate-in-front";

            var project = LegacyFixtures.Load(F);
            var screen = project.Tracks.Single(t => t.Name == "Screen");
            var copy = project.Tracks.Single(t => t.Name == "Screen copy");
            Assert.True(copy.Order > screen.Order, "the copy has moved out of the front");

            // both show 5 s of source; the mapping is the original's full frame, not the copy's
            AssertHosted(F, Cursor, 5 * Sec, "Screen", 5 * Sec);
            AssertHosted(F, Keyboard, 5 * Sec, "Screen", 5 * Sec);
            Assert.Equal(new[] { 0f, 0f, 1280f, 720f }, Golden(F, Cursor, 5 * Sec).Dest);

            // in the hole it falls to the copy, with no time offset. Scale .4 at (.25, .25): 512x288
            // centred on (320, 180)
            AssertHosted(F, Cursor, 25 * Sec, "Screen copy", 25 * Sec);
            AssertHosted(F, Keyboard, 25 * Sec, "Screen copy", 25 * Sec);
            Assert.Equal(new[] { 64f, 36f, 576f, 324f }, Golden(F, Cursor, 25 * Sec).Dest);
        }

