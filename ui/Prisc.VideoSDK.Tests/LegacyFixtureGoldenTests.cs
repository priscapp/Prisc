        [Theory]
        [MemberData(nameof(Fixtures))]
        public void Fixture_is_still_the_legacy_format_on_disk(string name)
        {
            using var doc = JsonDocument.Parse(File.ReadAllText(LegacyFixtures.ProjectPath(name)));
            var root = doc.RootElement;

            Assert.Equal(2, root.GetProperty("Version").GetInt32());

            foreach (var track in root.GetProperty("Tracks").EnumerateArray())
                Assert.False(track.TryGetProperty("GroupId", out _), "a track carries a group: regenerated by newer code?");

            var overlayKinds = new HashSet<string>();
            foreach (var item in root.GetProperty("Items").EnumerateArray())
            {
                var content = item.GetProperty("Content");
                var type = content.GetProperty("$type").GetString();
                if (type is not ("cursor" or "keyboard"))
                    continue;

                overlayKinds.Add(type);
                Assert.Equal(JsonValueKind.String, item.GetProperty("LinkGroupId").ValueKind);
                Assert.False(content.TryGetProperty("SourceInTicks", out _), "an overlay carries a clock: regenerated by newer code?");
            }

            Assert.Equal(new[] { "cursor", "keyboard" }, overlayKinds.OrderBy(k => k));
        }

