        [Theory]
        [MemberData(nameof(Fixtures))]
        public void Resolver_reproduces_the_goldens(string name)
        {
            var project = LegacyFixtures.Load(name);
            foreach (var expected in LegacyFixtures.ReadGolden(name))
            {
                var row = project.Tracks.Single(t => t.Id == expected.Track);
                var actual = OverlayGoldenResolver.Resolve(project, row, expected.T, W, H);

                var at = $"{name}: {expected.Kind} at {expected.T}";
                Assert.True(expected.Active == actual.Active, at);
                Assert.True(expected.Host == actual.Host, at);
                Assert.True(expected.SourceTicks == actual.SourceTicks, at);
                Assert.True(expected.Speed == actual.Speed, at);
                AssertRect(expected.Src, actual.Src, at);
                AssertRect(expected.Dest, actual.Dest, at);
            }
        }

        [Theory]
        [MemberData(nameof(Fixtures))]
        public void Migration_leaves_each_overlay_on_the_moment_its_old_host_showed(string name)
        {
            var project = LegacyFixtures.Load(name);
            var checkedSamples = 0;
            foreach (var sample in LegacyFixtures.ReadGolden(name).Where(s => s.Host != null))
            {
                var overlay = project.Items.Single(i => i.TrackId == sample.Track && i.Covers(sample.T));
                var host = project.Items.Single(i => i.TrackId == sample.Host && i.Covers(sample.T));
                var clock = (SourceClockContent)overlay.Content;

                Assert.Equal(sample.SourceTicks, FrameComposer.SourceTimeTicks(clock, overlay, sample.T));
                Assert.Equal(sample.SourceTicks, FrameComposer.SourceTimeTicks((MediaContent)host.Content, host, sample.T));
                checkedSamples++;
            }

            Assert.True(checkedSamples > 20, $"{name}: only {checkedSamples} samples had a host");
        }

        private static void AssertRect(float[] expected, float[] actual, string at)
        {
            if (expected == null || actual == null)
            {
                Assert.True(expected == null && actual == null, at);
                return;
            }

            for (var i = 0; i < 4; i++)
                Assert.True(Math.Abs(expected[i] - actual[i]) < 0.01f, $"{at}: rect [{i}] {actual[i]}, expected {expected[i]}");
        }

