        /// <summary>The clips on a row, as (start, length, source in-point) in seconds.</summary>
        private static (double, double, double)[] Parts<T>(Project project) where T : SourceClockContent =>
            project.Items.Where(i => i.Content is T)
                .Select(i => (i.TimelineStartTicks / (double)Sec, i.DurationTicks / (double)Sec,
                    ((T)i.Content).SourceInTicks / (double)Sec))
                .ToArray();

