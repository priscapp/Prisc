        [Theory]
        [MemberData(nameof(Fixtures))]
        public void Composer_draws_the_pointer_where_the_golden_says(string name)
        {
            var project = LegacyFixtures.Load(name);
            var capture = InputCapture.Get(project.Sources[0].InputCapturePath);
            var cursorRow = RowHolding<CursorContent>(project);
            HideOthers(project, cursorRow);

            using var canvas = new PixelCanvas();
            var located = 0;
            var absent = 0;
            foreach (var sample in LegacyFixtures.ReadGolden(name).Where(s => s.Track == cursorRow.Id))
            {
                canvas.Compose(project, sample.T);
                var box = canvas.BoundingBox((b, g, r) => r > 128 && b > 128 && g < 64);
                var at = $"{name} at {sample.T}";

                if (sample.Dest == null)
                {
                    Assert.True(box == null, at + ": drew a pointer with no host");
                    absent++;
                    continue;
                }

                var frame = capture.Frames[capture.LatestAtOrBefore(sample.SourceTicks.Value / (double)TimeSpan.TicksPerMillisecond)];
                var scaleX = (sample.Dest[2] - sample.Dest[0]) / (sample.Src[2] - sample.Src[0]);
                var scaleY = (sample.Dest[3] - sample.Dest[1]) / (sample.Src[3] - sample.Src[1]);
                var left = sample.Dest[0] + (frame.X - sample.Src[0]) * scaleX;
                var top = sample.Dest[1] + (frame.Y - sample.Src[1]) * scaleY;
                var right = left + 16 * scaleX;
                var bottom = top + 16 * scaleY;

                // the composer clips the sprite to the picture, and the picture may be sliding in
                // from off the canvas; a sprite cut by either has no whole box to compare
                var clipLeft = Math.Max(sample.Dest[0], 0);
                var clipTop = Math.Max(sample.Dest[1], 0);
                var clipRight = Math.Min(sample.Dest[2], W);
                var clipBottom = Math.Min(sample.Dest[3], H);
                if (right <= clipLeft || left >= clipRight || bottom <= clipTop || top >= clipBottom)
                {
                    Assert.True(box == null, at + ": drew a pointer outside its picture");
                    absent++;
                }
                else if (left >= clipLeft && right <= clipRight && top >= clipTop && bottom <= clipBottom)
                {
                    Assert.True(box != null, at + ": drew no pointer");
                    Assert.InRange(box.Value.Left, left - PointerSlopPx, left + PointerSlopPx);
                    Assert.InRange(box.Value.Top, top - PointerSlopPx, top + PointerSlopPx);
                    Assert.InRange(box.Value.Right, right - PointerSlopPx, right + PointerSlopPx);
                    Assert.InRange(box.Value.Bottom, bottom - PointerSlopPx, bottom + PointerSlopPx);
                    located++;
                }
            }

            Assert.True(located >= 20, $"{name}: only {located} samples located the pointer");
        }

        [Theory]
        [MemberData(nameof(Fixtures))]
        public void Composer_shows_keystrokes_when_the_golden_time_has_them(string name)
        {
            var project = LegacyFixtures.Load(name);
            var keysRow = RowHolding<KeyboardContent>(project);
            HideOthers(project, keysRow);

            var path = project.Sources[0].InputCapturePath;
            var keyboard = (KeyboardContent)project.Items.First(i => i.TrackId == keysRow.Id).Content;
            var runs = KeyboardLayout.GetRuns(path, keyboard.PauseBreakMs, keyboard.Filter);
            Assert.NotEmpty(runs);

            using var canvas = new PixelCanvas();
            var shown = 0;
            var quiet = 0;
            foreach (var sample in LegacyFixtures.ReadGolden(name).Where(s => s.Track == keysRow.Id))
            {
                canvas.Compose(project, sample.T);
                var ink = canvas.BoundingBox((b, g, r) => b > 16 || g > 16 || r > 16) != null;

                var expected = false;
                if (sample.Active)
                {
                    var item = project.Items.Single(i => i.TrackId == keysRow.Id
                        && sample.T >= i.TimelineStartTicks && sample.T < i.TimelineEndTicks);
                    expected = KeyboardLayout.VisibleRowsAt(runs,
                        sample.SourceTicks.Value / (double)TimeSpan.TicksPerMillisecond, sample.Speed.Value,
                        keyboard.LingerMs, KeystrokeRenderer.RowMs(item.Entry), KeystrokeRenderer.RowMs(item.Exit)).Count > 0;
                }

                Assert.True(expected == ink, $"{name} at {sample.T}: rows expected {expected}, ink {ink}");
                if (ink)
                    shown++;
                else
                    quiet++;
            }

            Assert.True(shown > 0 && quiet > 0, $"{name}: {shown} shown, {quiet} quiet, which tells nothing");
        }

        private static Track RowHolding<T>(Project project) where T : ItemContent =>
            project.Tracks.Single(t => project.Items.Any(i => i.TrackId == t.Id && i.Content is T));

        /// <summary>Leaves one overlay row composing: a row's pixels should answer for that row
        /// alone. Screen rows draw nothing here anyway, having no frames to draw.</summary>
        private static void HideOthers(Project project, Track keep)
        {
            foreach (var row in OverlayGoldenResolver.OverlayRows(project))
                row.Hidden = row.Id != keep.Id;
        }

        private sealed class PixelCanvas : IDisposable
        {
            private readonly CpuSurfaceFactory _factory = new CpuSurfaceFactory();
            private readonly SKSurface _surface;
            private readonly IntPtr _native = Marshal.AllocHGlobal(W * H * 4);
            private readonly byte[] _pixels = new byte[W * H * 4];

            public PixelCanvas()
            {
                _surface = _factory.CreateSurface(W, H);
            }

            /// <summary>Composes with no frame source, so media draws nothing and only the overlay
            /// row is left on the black canvas.</summary>
            public void Compose(Project project, long t)
            {
                FrameComposer.Compose(project, t, null, _surface.Canvas, W, H);
                Assert.True(_factory.TryReadPixels(_surface, W, H, _native, W * 4));
                Marshal.Copy(_native, _pixels, 0, _pixels.Length);
            }

            public (int Left, int Top, int Right, int Bottom)? BoundingBox(Func<byte, byte, byte, bool> match)
            {
                int left = int.MaxValue, top = int.MaxValue, right = -1, bottom = -1;
                for (var y = 0; y < H; y++)
                {
                    for (var x = 0; x < W; x++)
                    {
                        var i = (y * W + x) * 4;
                        if (!match(_pixels[i], _pixels[i + 1], _pixels[i + 2]))
                            continue;

                        left = Math.Min(left, x);
                        top = Math.Min(top, y);
                        right = Math.Max(right, x + 1);
                        bottom = Math.Max(bottom, y + 1);
                    }
                }

                return right < 0 ? null : (left, top, right, bottom);
            }

            public void Dispose()
            {
                _surface.Dispose();
                _factory.Dispose();
                Marshal.FreeHGlobal(_native);
            }
        }

        // ---------------------------------------------------------------- numbers worked by hand

        private static OverlaySample Golden(string fixture, string kind, long t) =>
            LegacyFixtures.ReadGolden(fixture).Single(s => s.Kind == kind && s.T == t);

        private static Guid RowId(string fixture, string name) =>
            LegacyFixtures.Load(fixture).Tracks.Single(t => t.Name == name).Id;

        private static void AssertHosted(string fixture, string kind, long t, string hostRow, long sourceTicks,
            double speed = 1.0)
        {
            var sample = Golden(fixture, kind, t);
            Assert.True(sample.Active);
            Assert.Equal(RowId(fixture, hostRow), sample.Host);
            Assert.Equal(sourceTicks, sample.SourceTicks);
            Assert.Equal(speed, sample.Speed);
        }

        private const string Cursor = OverlayGoldenResolver.CursorKind;
        private const string Keyboard = OverlayGoldenResolver.KeyboardKind;

        [Fact]
        public void Ctrl_k_slices_map_through_their_own_placement_and_clock()
        {
            const string F = "ctrl-k-recording";

            // Scale .75 at (.4, .45), cropped 10% left and 5% top: 1152x684 of capture on 960x570
            AssertHosted(F, Cursor, 5 * Sec, "Screen", 5 * Sec);
            Assert.Equal(new[] { 128f, 36f, 1280f, 720f }, Golden(F, Cursor, 5 * Sec).Src);
            Assert.Equal(new[] { 32f, 39f, 992f, 609f }, Golden(F, Cursor, 5 * Sec).Dest);

            // a linear 2 s SlideUp: below its place halfway through, in place once done
            AssertHosted(F, Cursor, 11 * Sec, "Screen", 11 * Sec);
            var sliding = Golden(F, Cursor, 11 * Sec).Dest;
            Assert.Equal(0f, sliding[0]);
            Assert.True(sliding[1] > 0);
            Assert.Equal(new[] { 0f, 0f, 1280f, 720f }, Golden(F, Cursor, 13 * Sec).Dest);

            // the hole the drag opened, then the moved slice 2 s behind its source
            Assert.False(Golden(F, Cursor, 26 * Sec).Active);
            Assert.False(Golden(F, Keyboard, 26 * Sec).Active);
            AssertHosted(F, Cursor, 30 * Sec, "Screen", 28 * Sec);
            AssertHosted(F, Keyboard, 30 * Sec, "Screen", 28 * Sec);
        }

        [Fact]
        public void One_overlay_clip_follows_screen_clips_that_jump_in_source_time()
        {
            const string F = "overlay-discontinuous";

            AssertHosted(F, Cursor, 5 * Sec, "Screen", 5 * Sec);
            AssertHosted(F, Cursor, 15 * Sec, "Screen", 25 * Sec);
            AssertHosted(F, Keyboard, 15 * Sec, "Screen", 25 * Sec);

            // past the screen's end the cursor has nothing to draw on and the keyboard runs on
            // its clip's own time
            var cursor = Golden(F, Cursor, 55 * Sec);
            Assert.True(cursor.Active);
            Assert.Null(cursor.Host);
            Assert.Null(cursor.SourceTicks);
            var keys = Golden(F, Keyboard, 55 * Sec);
            Assert.Null(keys.Host);
            Assert.Equal(55 * Sec, keys.SourceTicks);
        }

        [Fact]
        public void Overlays_hold_on_a_freeze_host()
        {
